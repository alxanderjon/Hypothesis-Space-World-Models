for name in ("OMP_NUM_THREADS", "OPENBLAS_NUM_THREADS", "MKL_NUM_THREADS",
             "VECLIB_MAXIMUM_THREADS", "NUMEXPR_NUM_THREADS"):
    os.environ[name] = "1"

import numpy as np
import torch

from experiments import validate_d5_production_pipeline as production
from experiments import expand_chronological_archive_handoff_dataset as expanded
from experiments.kepler import run_four_parameter_peelback as staged
from experiments.sho import run_stage1b_n3_gradient_polishing as polish
from experiments.sho.deterministic_full_k_framework import hashes


torch.set_default_dtype(torch.float64)
torch.set_num_threads(1)

ROOT = Path("outputs/n3_float64_stagnation_tail_validation")
UNRESOLVED = Path(
    "outputs/n1_candidate_handoff_supervision_uncapped_n3/"
    "handoff_promotion_unresolved.jsonl"
)
CAP_REPORT = Path("outputs/n3_accepted_step_cap_validation/report.json")
CALIBRATION_REPORT = Path("outputs/n3_float64_stagnation_tail_rule/report.json")
EXPANDED = Path("outputs/chronological_archive_handoff_supervision_expanded")


def atomic_json(path: Path, value) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_suffix(path.suffix + ".tmp")
    temporary.write_text(json.dumps(value, indent=2, allow_nan=False) + "\n")
    temporary.replace(path)


def run_kepler(case_id: int, theta: list[float], loss: float):
    trajectory, _ = production._kepler_case(case_id)
    _, objective = production._objectives("kepler5", trajectory)
    lower, upper, teacher = production._config("kepler5")
    _, _, run_n3 = staged._make_n3(objective, lower, upper)
    endpoint = polish.N2Endpoint(
        0, np.asarray(theta, np.float64), float(loss),
        "saved_validation_endpoint", "kepler5", False,
    )
    result = run_n3(endpoint, torch.empty(0))
    final = result.theta_history[-1]
    rollout = production._rollout("kepler5", trajectory, final)
    return {
        "accepted_steps": int(result.accepted_steps),
        "stop_reason": result.stop_reason,
        "final_theta": final.tolist(),
        "final_loss": float(result.loss_history[-1]),
        "parameter_l2_error": float(np.linalg.norm(final - teacher)),
        "continuation_max_error": rollout["continuation_max_error"],
    }


def replay_case186(query: dict) -> dict:
    manifest = json.loads((EXPANDED / "manifest.json").read_text())
    spec = next(row for row in manifest["trajectories"]
                if row["system"] == "reflection_ball" and row["case_id"] == 186)
    trajectory, _ = expanded.trajectory_for(spec)
    _, objective = production._objectives("reflection_ball", trajectory)
    lower, upper, _ = production._config("reflection_ball")
    _, _, run_n3 = staged._make_n3(objective, lower, upper)
    endpoint = polish.N2Endpoint(
        0, np.asarray(query["n2_endpoint"], np.float64), float(query["n2_loss"]),
        "case186_saved_n2_endpoint", "reflection_ball", False,
    )
    result = run_n3(endpoint, torch.empty(0))
    return {
        "accepted_steps": int(result.accepted_steps),
        "stop_reason": result.stop_reason,
        "final_theta": result.theta_history[-1].tolist(),
        "final_loss": float(result.loss_history[-1]),
    }


def main() -> None:
    before = hashes()
    calibration = json.loads(CALIBRATION_REPORT.read_text())
    joint = calibration["full_corpus_replay"]["joint_by_cohort"]
    expected_cohorts = {
        "successful_direct_n3": (35, 0),
        "ordinary_nonconverged_genuine_stop": (192, 0),
        "ordinary_nonconverged_resource_cap": (93, 0),
        "normal_high_precision": (10, 0),
    }
    for cohort, (count, triggered) in expected_cohorts.items():
        assert joint[cohort]["trajectories"] == count
        assert joint[cohort]["triggered_trajectories"] == triggered

    unresolved = [json.loads(line) for line in UNRESOLVED.read_text().splitlines()]
    aliases = []
    for index, row in enumerate(unresolved, 1):
        replay = run_kepler(
            int(row["case_id"]), row["label_n2_endpoint"], row["label_n2_loss"])
        replay.update(case_id=int(row["case_id"]), example_id=row["example_id"])
        aliases.append(replay)
        print("alias", index, len(unresolved), row["case_id"],
              replay["accepted_steps"], replay["stop_reason"], flush=True)
    assert len(aliases) == 15
    # These starts now use the previously integrated box-QP solver.  It may
    # reach an older genuine stop before reproducing a tail generated by the
    # historical direction path; the saved historical tails themselves are
    # checked by the calibrated full-corpus replay above.
    assert all(row["stop_reason"] in {
        polish.FLOAT64_STAGNATION_STOP_REASON,
        "floating_point_no_further_improvement",
        "backtracking_no_improvement",
    } for row in aliases)

    cap = json.loads(CAP_REPORT.read_text())
    cap_ids = {4, 31, 40, 47, 52, 54}
    cap_controls = []
    for saved in cap["cases"]:
        if saved["system"] != "kepler5" or int(saved["case_id"]) not in cap_ids:
            continue
        source = json.loads(Path(saved["source_path"]).read_text())
        handoff = source["successful_archived_handoff"]
        replay = run_kepler(
            int(saved["case_id"]), handoff["n2_endpoint"], handoff["n2_loss"])
        expected = saved["cap_suppressed"]
        exact = (
            replay["accepted_steps"] == expected["accepted_steps"]
            and replay["stop_reason"] == expected["stop_reason"]
            and np.array_equal(
                np.asarray(replay["final_theta"], np.float64).view(np.uint64),
                np.asarray(expected["final_theta"], np.float64).view(np.uint64),
            )
            and np.float64(replay["final_loss"]).view(np.uint64)
            == np.float64(expected["final_loss"]).view(np.uint64)
        )
        cap_controls.append(dict(case_id=int(saved["case_id"]), exact=bool(exact),
                                 replay=replay))
        print("cap-control", saved["case_id"], replay["accepted_steps"],
              replay["stop_reason"], "exact", exact, flush=True)
    assert len(cap_controls) == 6 and all(row["exact"] for row in cap_controls)

    case186_path = (EXPANDED / "query_cache/reflection_ball/case_00186/"
                    "n00002_i00002.json")
    case186 = json.loads(case186_path.read_text())
    assert not case186["target_good"]
    assert case186["n3_stop_reason"] == polish.FLOAT64_STAGNATION_STOP_REASON
    assert case186["n3_accepted_steps"] == 6
    case186_replay = replay_case186(case186)
    assert case186_replay["stop_reason"] == polish.FLOAT64_STAGNATION_STOP_REASON
    assert case186_replay["accepted_steps"] == 6
    assert np.array_equal(
        np.asarray(case186_replay["final_theta"], np.float64).view(np.uint64),
        np.asarray(case186["final_theta"], np.float64).view(np.uint64),
    )
    assert (np.float64(case186_replay["final_loss"]).view(np.uint64)
            == np.float64(case186["final_loss"]).view(np.uint64))

    report = {
        "implementation": {
            "loss_decrease_ULPs": (
                "(previous_loss - accepted_loss) / "
                "abs(np.spacing(np.float64(previous_loss)))"
            ),
            "full_predicted_decrease_ULPs": (
                "-box_qp.quadratic_value / "
                "abs(np.spacing(np.float64(previous_loss)))"
            ),
            "per_accepted_step_condition": (
                "loss_decrease_ULPs <= 512 AND "
                "full_predicted_decrease_ULPs > 512"
            ),
            "persistence": 3,
            "reset": "zero immediately after any accepted step failing either condition",
            "stop_reason": polish.FLOAT64_STAGNATION_STOP_REASON,
        },
        "saved_corpus_replay": {
            "case186_detected": True,
            "kepler_tails_detected": 15,
            "successful_direct_controls": joint["successful_direct_n3"],
            "normal_high_precision_controls": joint["normal_high_precision"],
            "ordinary_genuine_stop_controls": joint[
                "ordinary_nonconverged_genuine_stop"],
            "resource_limited_controls": joint[
                "ordinary_nonconverged_resource_cap"],
            "false_positives": calibration["full_corpus_replay"][
                "false_positive_trajectories"],
        },
        "production_kepler_alias_replays": aliases,
        "production_kepler_alias_replay_note": (
            "The corrected box-QP path reaches an existing genuine stop before "
            "the historical direction path's saved stagnation tail in these starts."
        ),
        "formerly_cap_limited_correct_basin_controls": cap_controls,
        "case186": case186,
        "case186_direct_production_replay": case186_replay,
        "checkpoint_hashes_unchanged": before == hashes(),
    }
    atomic_json(ROOT / "report.json", report)
    print(json.dumps({
        "aliases": len(aliases),
        "alias_step_range": [min(row["accepted_steps"] for row in aliases),
                             max(row["accepted_steps"] for row in aliases)],
        "cap_controls_exact": sum(row["exact"] for row in cap_controls),
        "case186": {"steps": case186["n3_accepted_steps"],
                    "stop": case186["n3_stop_reason"],
                    "good": case186["target_good"]},
        "checkpoint_hashes_unchanged": report["checkpoint_hashes_unchanged"],
    }, indent=2))


if __name__ == "__main__":
    main()
