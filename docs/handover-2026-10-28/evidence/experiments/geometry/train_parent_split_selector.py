"""Train only canonical parent KEEP/REPLACE routing; no recursive execution."""
import csv
import json
import time
from collections import defaultdict
from pathlib import Path

import numpy as np
import torch
from torch import nn

from experiments.geometry import refine_sqrt_failure_cases as ref
from experiments.geometry.train_interval_minimum_reducer import (
    IntervalMinimumReducer, TABLE, LABELS, synthetic_sequences, transition_metrics,
)
from experiments.geometry.train_subpiece_minimum_selector import SubpieceSelector, canonical
from experiments.geometry.validate_terminal_candidate_full import original_parents
from experiments.sho.audit_fixed_allocation_intervals import Audit
from experiments.sho.train_finite_split_score_smoke import load_frozen
from experiments.sho.smoke_artifacts import save_checkpoint

ROOT = ref.ROOT
OUT = ROOT / 'parent_split_selector_training'
SUB = ROOT / 'subpiece_minimum_selector_training'
INTERVAL = ROOT / 'interval_minimum_reducer_training'
SEED = 28342026


class ParentSplitSelector(IntervalMinimumReducer):
    """New learned head; reuse unchanged frozen global-best feature computation.

    The caller supplies canonical (axis, cut, identity) order. No teacher labels
    or direct score argmin are used in normal learned inference.
    """


def safe_json(value):
    return json.dumps(value, indent=2, default=lambda x: x.item() if isinstance(x, np.generic) else str(x))


def load_locked(folder, status_name):
    meta = json.loads((folder / 'results.json').read_text())
    assert meta['status'] == 'LOCKED'
    checkpoint = Path(meta['checkpoint'])
    assert ref.sha(checkpoint) == meta['checkpoint_sha256']
    manifest = folder / status_name
    assert ref.sha(manifest) == meta['lock_manifest_sha256']
    return meta, torch.load(checkpoint, weights_only=False)['state_dict']


def run():
    started = time.monotonic()
    torch.set_num_threads(1)
    torch.manual_seed(SEED)
    OUT.mkdir(parents=True, exist_ok=False)
    protected = {str(p): ref.sha(p) for p in ROOT.rglob('*.pt')}
    protected.update({str(p): ref.sha(p) for p in ROOT.rglob('*.json')
                      if any(s in p.name for s in ('manifest', 'locked', 'validated'))})
    source_paths = [SUB/'frozen_candidate_scores.csv', INTERVAL/'interval_winner_replay.csv',
                    Path('experiments/geometry/verify_continuous_cut_recursive_selector.py'),
                    Path('experiments/geometry/train_interval_minimum_reducer.py'),
                    Path('experiments/geometry/train_subpiece_minimum_selector.py')]
    protected.update({str(p): ref.sha(p) for p in source_paths})
    audit_text = '''Parent teacher audit
Source: verify_continuous_cut_recursive_selector.py, select() and canonical().
Axes are generated by range(d): 0 through d-1. Allocation intervals are
generated by range(1,n): increasing left-child count k. Within an interval,
active subpieces follow increasing cut bounds, with left/right endpoints and
stationary candidates where present. Shared endpoint identities are retained.
The final selector does not simply retain this insertion order: candidates
are sorted by (axis, cut ascending, identity lexicographic).

The teacher first computes the global strict minimum b, then selects the first
ordered candidate whose score <= b + 1e-12 * max(1,b). Exact ties and equivalent
later challengers therefore retain the earlier canonical identity.

This experiment takes the learned winner of each interval, orders those winners
by exactly the same key, reuses frozen scalar min/equivalence computations, and
learns only the sequential KEEP/REPLACE head on two eligibility indicators.
It is a two-pass canonical reducer. A memoryless pairwise tolerance rule is not
substituted, because tolerance equivalence is not transitive.

Full original candidate pools remain the independent teacher reference, so a
change caused by reducing subpieces/intervals before the parent cannot be hidden.
Scores/coordinates are read from the previous frozen candidate cache; the locked
subpiece selector and locked interval reducer are executed again. No candidate
construction, score, allocation, or recursive control-flow training occurs.
'''
    (OUT/'parent_teacher_audit.txt').write_text(audit_text)
    sm, sw = load_locked(SUB, 'subpiece_minimum_selector_locked.json')
    im, iw = load_locked(INTERVAL, 'interval_minimum_reducer_locked.json')
    _, execution, _ = load_frozen()
    sub = SubpieceSelector(execution)
    sub.route.load_state_dict(sw)
    sub.eval().requires_grad_(False)
    interval = IntervalMinimumReducer(sub)
    interval.head.load_state_dict(iw)
    interval.eval().requires_grad_(False)
    parent = ParentSplitSelector(sub)  # Only this fresh head is optimized.
    initial = {k: v.detach().tolist() for k, v in parent.head.state_dict().items()}

    subpools, full_parent = defaultdict(list), defaultdict(list)
    for row in csv.DictReader((SUB/'frozen_candidate_scores.csv').open()):
        if row['group'] not in ('archive_geometry', 'fresh_geometry'):
            continue
        e = dict(row)
        for key in ('parent', 'axis', 'k'): e[key] = int(e[key])
        for key in ('cut', 'teacher_score', 'score'): e[key] = float(e[key])
        subpools[(e['group'], e['case'])].append(e)
        full_parent[(e['group'], e['parent'])].append(e)
    slots, scores, valid = [], [], []
    for pool in subpools.values():
        pp = sorted(pool, key=lambda e: (e['cut'], e['identity']))
        assert len(pp) in (2, 3)
        ss = [pp[0], pp[-1], pp[1] if len(pp) == 3 else None]
        slots.append(ss)
        scores.append([r['score'] if r else 0. for r in ss])
        valid.append([r is not None for r in ss])
    scores, valid = np.array(scores), np.array(valid)
    subchoices = sub.select(sub.normalize(scores, valid), valid)
    interval_pools = defaultdict(list)
    for ss, j in zip(slots, subchoices):
        e = ss[j]
        assert e is not None
        interval_pools[(e['group'], e['parent'], e['axis'], e['k'])].append(e)
    interval_keys = sorted(interval_pools)
    interval_lists = [sorted(interval_pools[k], key=lambda e: (e['axis'], e['cut'], e['identity'])) for k in interval_keys]
    ichosen, _, _ = interval.reduce([np.array([e['score'] for e in pool]) for pool in interval_lists], shadow=True)
    parent_pools = defaultdict(list)
    prior = {(r['group'], int(r['parent']), int(r['axis']), int(r['allocation'])): r
             for r in csv.DictReader((INTERVAL/'interval_winner_replay.csv').open())}
    for key, pool, j in zip(interval_keys, interval_lists, ichosen):
        e = pool[j]
        assert e['identity'] == prior[key]['learned_identity'] and e['cut'] == float(prior[key]['learned_cut'])
        parent_pools[key[:2]].append(e)
    keys = sorted(parent_pools)
    lists = [sorted(parent_pools[k], key=lambda e: (e['axis'], e['cut'], e['identity'])) for k in keys]
    seq = [np.array([e['score'] for e in pool]) for pool in lists]
    is_archive = np.array([k[0] == 'archive_geometry' for k in keys])
    assert is_archive.sum() == 106 and (~is_archive).sum() == 8
    # Split by whole archived parent, not individual transitions.
    holdout = is_archive & (np.arange(len(keys)) % 5 == 0)
    _, trace, _ = parent.reduce(seq, shadow=True, teacher_actions=True)
    ids = trace[:, 0].astype(int)
    fit = is_archive[ids] & ~holdout[ids]
    train_seq, _ = synthetic_sequences(SEED+1, 4096)
    _, trsyn, _ = parent.reduce(train_seq, shadow=True, teacher_actions=True)
    x = np.concatenate((TABLE, trace[fit, 3:5], trsyn[:, 3:5]))
    y = np.concatenate((LABELS, trace[fit, 5].astype(int), trsyn[:, 5].astype(int)))
    unique, inverse = np.unique(np.column_stack((x, y)), axis=0, return_inverse=True)
    counts = np.bincount(inverse).astype(float)
    weights = .5*counts/counts.sum() + .5/len(counts)
    xt = torch.from_numpy(unique[:, :2]); yt = torch.from_numpy(unique[:, 2].astype(int)); wt = torch.from_numpy(weights)
    opt = torch.optim.Adam(parent.head.parameters(), lr=.06)
    history = []
    for update in range(1, 2001):
        opt.zero_grad()
        loss = (nn.functional.cross_entropy(parent.head(xt), yt, reduction='none')*wt).sum()
        loss.backward(); opt.step()
        with torch.no_grad():
            logits = parent.head(xt)
            value = float((nn.functional.cross_entropy(logits, yt, reduction='none')*wt).sum())
            errors = int((logits.argmax(1) != yt).sum())
        if update % 10 == 0 or (errors == 0 and value < .01):
            history.append(dict(update=update,loss=value,truth_errors=errors))
        if errors == 0 and value < .01: break
    parent.eval().requires_grad_(False)
    checkpoint = OUT/'parent_selector_before_evaluation.pt'
    digest = save_checkpoint(checkpoint, dict(state_dict=parent.head.state_dict(), optimizer_state=opt.state_dict(),
        initial_parameters=initial, seed=SEED, updates=update, architecture='float64 Linear(2,2)',
        features=['current_eligible_against_global_best','challenger_eligible_against_global_best'],
        actions=['KEEP_CURRENT','REPLACE_CURRENT'], subpiece_sha256=sm['checkpoint_sha256'], interval_sha256=im['checkpoint_sha256']))
    ref.write_csv(OUT/'training_history.csv', history)
    print(safe_json(dict(stage='saved_before_evaluation', updates=update, checkpoint_sha256=digest)), flush=True)

    chosen, trace, _ = parent.reduce(seq, shadow=True)
    fresh_seq, kinds = synthetic_sequences(SEED+2, 8192)
    _, st, _ = parent.reduce(fresh_seq, shadow=True)
    ids = trace[:, 0].astype(int)
    reports = dict(complete_rule=dict(transitions=4,total_errors=int(np.sum(parent.actions(TABLE)!=LABELS))),
        archived=transition_metrics(trace[is_archive[ids]]), heldout_archived=transition_metrics(trace[holdout[ids]]),
        fresh_parent=transition_metrics(trace[~is_archive[ids]]), fresh_synthetic=transition_metrics(st))
    for name in np.unique(kinds):
        reports['synthetic_'+name] = transition_metrics(st[kinds[st[:,0].astype(int)]==name])
    records = original_parents()
    fresh_records = json.loads((ROOT/'stationary_terminal_candidate_training/fresh_parents.json').read_text())
    allocator_audit = Audit()
    results, ordered = [], []
    for i, (key, pool, index) in enumerate(zip(keys, lists, chosen)):
        teacher = canonical(full_parent[key])
        learned = pool[index]
        record = records[key[1]] if key[0]=='archive_geometry' else fresh_records[str(key[1])]
        counts_out = []
        for candidate in (teacher, learned):
            allocator_audit.setup(record, candidate['axis'])
            counts_out.append(allocator_audit.counts(candidate['cut'])[0].tolist())
        best = min(e['teacher_score'] for e in full_parent[key])
        tol = 1e-12*max(1.,best)
        outside = learned['teacher_score'] > best+tol
        sides = np.array(record['upper'])-record['lower']
        results.append(dict(group=key[0],parent=key[1],heldout=bool(holdout[i]),dimension=record['d'],budget=record['n'],
            side_lengths=json.dumps(sides.tolist()),aspect=float(sides.max()/sides.min()),interval_winners=len(pool),
            teacher_axis=teacher['axis'],learned_axis=learned['axis'],axis_changed=teacher['axis']!=learned['axis'],
            teacher_cut=teacher['cut'],learned_cut=learned['cut'],coordinate_changed=teacher['cut']!=learned['cut'],
            coordinate_ULP_difference=abs(int(np.float64(teacher['cut']).view(np.uint64))-int(np.float64(learned['cut']).view(np.uint64))),
            teacher_counts=json.dumps(counts_out[0]),learned_counts=json.dumps(counts_out[1]),allocation_changed=counts_out[0]!=counts_out[1],
            teacher_interval_k=teacher['k'],learned_interval_k=learned['k'],interval_changed=teacher['k']!=learned['k'],
            teacher_identity=teacher['identity'],learned_identity=learned['identity'],identity_changed=teacher['identity']!=learned['identity'],
            teacher_best_score=best,teacher_selected_score=teacher['teacher_score'],learned_selected_teacher_score=learned['teacher_score'],
            learned_selected_score=learned['score'],teacher_score_penalty=max(0.,learned['teacher_score']-best),outside_equivalence=outside,
            equivalent_coordinate_difference=teacher['cut']!=learned['cut'] and not outside))
        ordered.extend(dict(parent_index=i,order=j,**e) for j,e in enumerate(pool))
    ref.write_csv(OUT/'parent_replay.csv', results)
    ref.write_csv(OUT/'ordered_parent_candidates.csv', ordered)
    ref.write_csv(OUT/'reducer_accuracy.csv', [dict(group=k,**v) for k,v in reports.items()])
    ref.write_csv(OUT/'learned_parameters.csv', [dict(parameter=k,values=json.dumps(v.tolist())) for k,v in parent.head.state_dict().items()])
    ref.write_csv(OUT/'truth_table.csv', [dict(current_eligible=int(s[0]),challenger_eligible=int(s[1]),teacher=int(t),learned=int(p)) for s,t,p in zip(TABLE,LABELS,parent.actions(TABLE))])
    np.savez_compressed(OUT/'reduction_transitions.npz',transitions=trace,synthetic_transitions=st,
        parent_keys=np.array([str(k) for k in keys]),heldout_parent=holdout,
        columns=np.array(['parent_index','challenger_index','current_index','current_eligible','challenger_eligible','teacher_action','learned_action','exact_tie','one_ULP','equivalence_boundary']))
    assert all(ref.sha(Path(p))==h for p,h in protected.items())
    def metrics(group):
        rr=[r for r in results if r['group']==group]
        return dict(parents=len(rr),exact_axis_matches=sum(not r['axis_changed'] for r in rr),
            exact_cut_matches=sum(not r['coordinate_changed'] for r in rr),exact_child_allocation_matches=sum(not r['allocation_changed'] for r in rr),
            equivalent_coordinate_differences=sum(r['equivalent_coordinate_difference'] for r in rr),
            candidate_identity_changes=sum(r['identity_changed'] for r in rr),score_changes_outside_equivalence=sum(r['outside_equivalence'] for r in rr),
            max_coordinate_ULP_difference=max(r['coordinate_ULP_difference'] for r in rr),
            dimensions=sorted(set(r['dimension'] for r in rr)),budgets=sorted(set(r['budget'] for r in rr)),
            interval_list_length_min=min(r['interval_winners'] for r in rr),interval_list_length_max=max(r['interval_winners'] for r in rr))
    bad=[r for r in results if any(r[k] for k in ('axis_changed','allocation_changed','identity_changed','outside_equivalence'))]
    passed=not bad and all(r['total_errors']==0 for r in reports.values())
    if bad:
        (OUT/'first_failure.json').write_text(safe_json(dict(parent=bad[0],candidates=full_parent[(bad[0]['group'],bad[0]['parent'])])))
    result=dict(operator='parent_split_selector',status='LOCKED' if passed else 'DIAGNOSTIC_ONLY_STOP',passed=passed,
        architecture='Frozen global minimum/equivalence pass then learned Linear(2,2) action head; 6 new float64 parameters',
        parameters={k:v.tolist() for k,v in parent.head.state_dict().items()},updates=update,seed=SEED,
        archived=metrics('archive_geometry'),fresh=metrics('fresh_geometry'),transition_metrics=reports,
        training_archived_parents=int((is_archive&~holdout).sum()),heldout_archived_parents=int(holdout.sum()),
        training_archived_transitions=int(fit.sum()),synthetic_training_sequences=4096,synthetic_fresh_sequences=8192,
        first_mismatch=bad[0] if bad else None,
        subpiece_checkpoint_sha256=sm['checkpoint_sha256'],interval_checkpoint_sha256=im['checkpoint_sha256'],
        checkpoint=str(checkpoint),checkpoint_sha256=digest,implementation_sha256=ref.sha(Path(__file__)),
        all_protected_hashes_unchanged=True,protected_files=len(protected),elapsed_seconds=time.monotonic()-started,
        scope='Cached frozen candidate scores/coordinates; rerun locked subpiece and interval inference; train only parent routing. Fresh geometric parents are prior validation parents, never used for this fitting. New independent synthetic sequences test routing.',
        no_recursion=True,no_search=True)
    if passed:
        manifest=OUT/'parent_split_selector_locked.json'
        manifest.write_text(safe_json(result));mh=ref.sha(manifest)
        manifest.with_suffix('.sha256').write_text(mh+'  '+manifest.name+'\n')
        result['lock_manifest_sha256']=mh
    (OUT/'results.json').write_text(safe_json(result))
    (OUT/'protected_hashes.json').write_text(safe_json(protected))
    (OUT/'parent_selector_summary.txt').write_text(safe_json(result))
    print(safe_json(result),flush=True)


if __name__=='__main__':
    run()
