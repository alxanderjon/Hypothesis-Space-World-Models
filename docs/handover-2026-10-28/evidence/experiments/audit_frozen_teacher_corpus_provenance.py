#!/usr/bin/env python3
"""Audit the provenance of the nominal 822-case teacher-validation corpus.

This is a read-only provenance audit.  It classifies saved outputs; it does
not run or modify the teacher/student implementations.
"""
from __future__ import annotations

import csv
import hashlib
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "outputs" / "frozen_822_corpus_provenance_audit"
FREEZE = ROOT / "outputs" / "deterministic_teacher_frozen" / "freeze_manifest.json"
READINESS = ROOT / "outputs" / "deterministic_teacher_readiness"
SHO = ROOT / "outputs" / "sho" / "stage1B" / "checkpointed_resource_edirect"
ARCHIVE = ROOT / "outputs" / "chronological_archive_handoff_supervision_expanded"


def digest(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load_json(path: Path):
    return json.loads(path.read_text())


def load_jsonl(path: Path):
    return [json.loads(line) for line in path.read_text().splitlines()]


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    freeze = load_json(FREEZE)
    readiness_manifest = load_json(READINESS / "manifest.json")
    sho_rows = load_json(SHO / "results_partial.json")
    archive_states = load_jsonl(ARCHIVE / "expanded_archive_states.jsonl")

    rows: list[dict] = []
    for row in sho_rows:
        rows.append({
            "corpus_partition": "prior_evidence_sho",
            "system": "full_k_sho",
            "case_id": int(row["case_id"]),
            "case_name": row["case"],
            "artifact": str(SHO / "results_partial.json"),
            "creation_source": "experiments/sho/generate_checkpointed_edirect_teacher_data.py",
            "source_manifest": "NONE_EMBEDDED",
            "classification": "LEGACY_ARTIFACT_REQUIRES_REGENERATION",
            "reason": (
                "Generated by the checkpoint/loss-gate pipeline before chronological "
                "archive probing and later frozen N2/N3 semantics; case 0 is a direct "
                "current-teacher mismatch."
            ),
        })

    for row in archive_states:
        if not row["target_any_good"]:
            continue
        cohort = row.get("cohort", "base_legacy_archive")
        rows.append({
            "corpus_partition": "prior_evidence_archive",
            "system": row["system"],
            "case_id": int(row["case_id"]),
            "case_name": row["state_id"],
            "artifact": str(ARCHIVE / "expanded_archive_states.jsonl"),
            "creation_source": (
                "experiments/build_chronological_archive_handoff_dataset.py"
                if cohort == "base_legacy_archive"
                else "experiments/expand_chronological_archive_handoff_dataset.py"
            ),
            "source_manifest": "PRE_FREEZE_ARCHIVE_MANIFEST_WITHOUT_FROZEN_TEACHER_HASH",
            "classification": "LEGACY_ARTIFACT_REQUIRES_REGENERATION",
            "reason": (
                "Generated before the exact SciPy-1.13.0 Powell integration; sampled "
                "saved N2 endpoints differ bitwise from the current frozen exact N2."
            ),
        })

    for spec in readiness_manifest["cases"]:
        system = spec["system"]
        case_id = int(spec["case_id"])
        artifact = READINESS / "cases" / system / f"case_{case_id:05d}" / "result.json"
        rows.append({
            "corpus_partition": "frozen_teacher_readiness_new",
            "system": system,
            "case_id": case_id,
            "case_name": f"{system}_readiness_{case_id:05d}",
            "artifact": str(artifact),
            "creation_source": "experiments/validate_deterministic_teacher_readiness.py",
            "source_manifest": str(FREEZE),
            "classification": "CURRENT_TEACHER_EQUIVALENT",
            "reason": (
                "Executed by the teacher-readiness pipeline with exact Powell N2, "
                "box-QP uncapped N3, stagnation stop, chronological archive, and "
                "absorbing success; source hashes are frozen and still match."
            ),
        })

    assert len(rows) == 822, len(rows)
    counts: dict[str, int] = {}
    by_system: dict[str, dict[str, int]] = {}
    for row in rows:
        classification = row["classification"]
        counts[classification] = counts.get(classification, 0) + 1
        by_system.setdefault(row["system"], {})
        target = by_system[row["system"]]
        target[classification] = target.get(classification, 0) + 1

    source_hash_checks = {}
    for path, expected in freeze["sources"].items():
        actual = digest(ROOT / path)
        source_hash_checks[path] = {
            "expected": expected, "actual": actual, "match": actual == expected,
        }

    report = {
        "scope": "provenance only; no teacher/student mutation and no 822-case replay",
        "authoritative_freeze_manifest": str(FREEZE),
        "authoritative_freeze_manifest_sha256": digest(FREEZE),
        "required_freeze_manifest_sha256": "66cfe5f07347bdadfb11baef61f4212918c42102cf48accf0d6563ab96c88759",
        "freeze_hash_matches_requirement": digest(FREEZE) == "66cfe5f07347bdadfb11baef61f4212918c42102cf48accf0d6563ab96c88759",
        "frozen_source_hash_checks": source_hash_checks,
        "counts": counts,
        "counts_by_system": by_system,
        "partition_counts": {
            "prior_evidence_sho": 256,
            "prior_evidence_archive_reflection_ball": 182,
            "prior_evidence_archive_kepler5": 192,
            "frozen_teacher_readiness_new": 192,
        },
        "provenance_finding": (
            "The readiness report combined 630 imported prior-evidence outputs with "
            "192 cases actually executed by the frozen teacher-readiness pipeline."
        ),
        "legacy_reasons": {
            "sho_256": [
                "Historical N1 stopped at a 100-evaluation checkpoint using loss/containment gates; it did not use chronological archive probing.",
                "Artifacts predate the exact N2 Powell integration and corrected current N3 semantics.",
                "SHO case 0 directly differs from current N3 when replayed from the same N2 endpoint (3 accepted steps historically, 2 currently).",
            ],
            "archive_374": [
                "Archive/absorbing and corrected uncapped box-QP N3 semantics are present.",
                "Artifacts were created before exact SciPy-1.13.0 Powell N2 was integrated.",
                "All 694 base site/count labels reused older N2 endpoint caches; expanded labels were also generated before exact-N2 integration.",
                "Four later sampled branches (ball 0, ball 2, Kepler 0, Kepler 143) all had cached endpoints unequal to current exact Powell endpoints.",
            ],
        },
        "sample_replays": {
            "sho_case_0_full_current_pipeline": {
                "historical": {"n1_evaluations": 100, "n2_evaluations": 196,
                    "n3_accepted_steps": 3,
                    "n3_stop_reason": "floating_point_no_further_improvement",
                    "final_theta": [5.887688867021595e-18, 1.0, -1.0, -0.21480188739480885],
                    "final_loss": 1.0754644919411023e-31},
                "current": {"n1_evaluations": 1, "archive_handoff_index": 0,
                    "n2_evaluations": 659,
                    "n2_endpoint": [-1.8447408244458172e-10, 0.9999999998947869,
                        -0.9999999999474132, -0.21480188752911328],
                    "n3_accepted_steps": 1,
                    "n3_stop_reason": "floating_point_no_further_improvement",
                    "final_theta": [1.43929240468589e-18, 1.0, -1.0, -0.21480188739480885],
                    "final_loss": 1.0756423237118773e-31},
                "same_saved_historical_n2_endpoint_current_n3": {
                    "accepted_steps": 2,
                    "stop_reason": "floating_point_no_further_improvement",
                    "final_theta": [1.4571912459988667e-18, 1.0, -1.0, -0.21480188739480885],
                    "final_loss": 1.0756423237118773e-31,
                },
            },
            "reflection_ball_case_0_n2_archive0": {
                "saved_n2_endpoint_matches_current": False,
                "historical_n3_steps": 5, "current_n3_steps": 4,
                "historical_final_loss": 1.003335335662488e-37,
                "current_final_loss": 1.8585768948434278e-37,
                "recovery_outcome_same": True, "final_bits_equal": False,
            },
            "kepler5_case_0_n3_archive2": {
                "saved_n2_endpoint_matches_current": False,
                "historical_n3_steps": 49, "current_n3_steps": 48,
                "historical_final_loss": 2.0946383745550155e-34,
                "current_final_loss": 8.861931584655835e-35,
                "recovery_outcome_same": True, "final_bits_equal": False,
            },
        },
        "conclusion": {
            "comparison_corpus_requires_refresh": True,
            "cases_to_regenerate": 630,
            "cases_reusable_without_regeneration": 192,
            "authoritative_future_reference": (
                "A regenerated per-case corpus whose outputs are produced under freeze "
                "manifest 66cfe5f...c88759, with each case recording that manifest hash, "
                "environment, source hashes, N1/archive/N2/N3 traces, and artifact hashes."
            ),
        },
    }

    (OUT / "report.json").write_text(json.dumps(report, indent=2) + "\n")
    with (OUT / "case_classification.csv").open("w", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=list(rows[0]))
        writer.writeheader(); writer.writerows(rows)


if __name__ == "__main__":
    main()
